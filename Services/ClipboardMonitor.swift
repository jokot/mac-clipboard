import Foundation
import Cocoa
import Combine

protocol ClipboardMonitorProtocol {
    var itemPublisher: AnyPublisher<ClipboardItem, Never> { get }
    func start()
    func stop()
    func ignoreCurrentChangeCount()
}

final class ClipboardMonitor: ClipboardMonitorProtocol {
    private let subject = PassthroughSubject<ClipboardItem, Never>()
    var itemPublisher: AnyPublisher<ClipboardItem, Never> { subject.eraseToAnyPublisher() }

    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            self?.pollPasteboard()
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func ignoreCurrentChangeCount() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func pollPasteboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        let frontmost = NSWorkspace.shared.frontmostApplication
        let sourceBundleID = frontmost?.bundleIdentifier

        // The list of apps, and the MaClip switch. A file copy can carry an icon image, so a
        // clip with file URLs is not an image here.
        let isImage = pb.availableType(from: [.png, .tiff]) != nil && (readFileURLs(from: pb)?.isEmpty ?? true)
        if AppSettings.skipsClip(from: sourceBundleID,
                                 excluded: AppSettings.shared.excludedBundleIDs,
                                 saveMaClipClips: AppSettings.shared.saveMaClipClips,
                                 isImage: isImage) {
            return
        }

        // Concealed UTI detection. Inspect types BEFORE reading data.
        let concealedUTIs: Set<String> = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.AutoGeneratedType",
            "com.apple.is-sensitive",
        ]
        let hasConcealedMark: Bool = {
            guard let types = pb.types else { return false }
            return types.contains { concealedUTIs.contains($0.rawValue) }
        }()

        // Read content (files > image > URL > text) — same priority as before. Secret detection
        // reads the raw text, before MaClip turns a link in the text into a URL clip.
        let content: ClipboardItemContent
        let text: String?
        if let urls = readFileURLs(from: pb), !urls.isEmpty {
            content = .file(urls)
            text = nil
        } else if let image = readImage(from: pb) {
            content = .image(ImageContent(source: .memory(image), cachedText: nil, cachedId: nil, cachedBarcode: nil))
            text = nil
        } else if let url = readURL(from: pb) {
            content = .url(url)
            text = url.absoluteString
        } else if let raw = readText(from: pb) {
            let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            content = URLUtils.linkURL(from: trimmed).map { .url($0) } ?? .text(raw)
            text = raw
        } else {
            return
        }

        let settings = AppSettings.shared
        let decision = SecretCapture.decide(text: text, hasConcealedMark: hasConcealedMark,
                                            findSecrets: settings.findSecrets,
                                            skipConcealed: settings.skipConcealedItems,
                                            timeout: settings.concealedClearTimeout, now: Date())
        guard case let .save(isConcealed, expiry, secretKind) = decision else { return }
        subject.send(ClipboardItem(
            date: Date(), content: content,
            sourceBundleID: sourceBundleID,
            isConcealed: isConcealed,
            concealedExpiresAt: expiry,
            secretKind: secretKind
        ))
    }

    private func readText(from pasteboard: NSPasteboard) -> String? {
        if let items = pasteboard.pasteboardItems, !items.isEmpty {
            let item = items[0]
            if let str = item.string(forType: .string) { return str }
        }
        return nil
    }

    private func readFileURLs(from pb: NSPasteboard) -> [URL]? {
        let opts: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        guard let objects = pb.readObjects(forClasses: [NSURL.self], options: opts) as? [URL],
              !objects.isEmpty else { return nil }
        return objects
    }

    private func readURL(from pasteboard: NSPasteboard) -> URL? {
        if let objs = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL], let url = objs.first {
            return url
        }
        if let items = pasteboard.pasteboardItems, let item = items.first {
            if let s = item.string(forType: .URL), let url = URL(string: s) { return url }
            // Some apps use public.url
            if let s = item.string(forType: NSPasteboard.PasteboardType("public.url")), let url = URL(string: s) { return url }
        }
        return nil
    }

    private func readImage(from pasteboard: NSPasteboard) -> NSImage? {
        // Try robust Cocoa reading first
        if let objs = pasteboard.readObjects(forClasses: [NSImage.self], options: nil) as? [NSImage],
           let img = objs.first {
            return img
        }
        // Fallback: inspect first pasteboard item data for common image types
        if let items = pasteboard.pasteboardItems, let item = items.first {
            if let data = item.data(forType: .tiff), let image = NSImage(data: data) {
                return image
            }
            if let data = item.data(forType: .png), let image = NSImage(data: data) {
                return image
            }
        }
        return nil
    }
}